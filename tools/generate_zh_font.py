"""Subset the bundled WenQuanYi 12px font losslessly; output an apply_patch or verify.

No system font or network dependency. Glyph payloads are copied unmodified.
Source: components/u8g2/csrc/u8g2_fonts.c, u8g2_font_wqy12_t_gb2312.
"""
import argparse
import ast
import re
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
TARGET='firmware/ui/zh_font.c'

def generate():
    source=(ROOT/'components/u8g2/csrc/u8g2_fonts.c').read_text(encoding='latin1')
    # Literal semicolons can occur inside strings: stop at the declaration terminator.
    part=source.split('const uint8_t u8g2_font_wqy12_t_gb2312[',1)[1]
    part=part[:re.search(r';\s*\n',part).start()]
    data=b''.join(ast.literal_eval('b'+s) for s in re.findall(r'"(?:\\.|[^"\\])*"',part)[1:])
    assert len(data) in (202689,202690),len(data)
    translations=(ROOT/'firmware/ui/ui_zh.c').read_text(encoding='utf8')
    values=re.findall(r'\{"[^"\n]*","([^"\n]*)"\}',translations)
    wanted={ord(c) for value in values for c in value if ord(c)>255}
    help_text=(ROOT/'firmware/ui/help_text.c').read_text(encoding='utf8')
    wanted.update(ord(c) for value in re.findall(r'"([^"\n]*)"',help_text) for c in value if ord(c)>255)
    def word(offset):return int.from_bytes(data[offset:offset+2],'big')
    def glyph(code):
        lookup=23+word(21);offset=lookup
        while True:
            offset+=word(lookup);end=word(lookup+2);lookup+=4
            if end>=code:break
        while word(offset):
            size=data[offset+2]
            assert size>=3
            if word(offset)==code:return data[offset:offset+size]
            offset+=size
        raise ValueError('Missing required glyph '+chr(code))
    # Keep original Latin records and offsets; replace Unicode lookup with one block.
    latin=data[23:23+word(21)]
    header=bytearray(data[:23]);header[0]=len(wanted)%256
    output=bytes(header)+latin+b'\x00\x04\xff\xff'+b''.join(glyph(c) for c in sorted(wanted))+b'\x00\x00'
    lines=['/* Generated by tools/generate_zh_font.py. Do not hand edit.',
           ' * WenQuanYi Bitmap Song 12, lossless glyph subset from bundled U8g2.',
           ' * See docs/zh_ui.md for source and font license. */','#include <stdint.h>',
           'const uint8_t halfstep_zh_font[]={']
    for i in range(0,len(output),20):lines.append('    '+','.join(f'0x{b:02x}' for b in output[i:i+20])+',')
    lines+=['};','']
    return '\n'.join(lines),len(wanted),len(output)

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--patch',action='store_true');args=ap.parse_args()
    text,count,size=generate()
    if args.patch:
        path=ROOT/TARGET
        prefix='*** Update File: '+str(path)+'\n@@\n'+'\n'.join('-'+s for s in path.read_text(encoding='utf8').splitlines())+'\n' if path.exists() else '*** Add File: '+str(path)+'\n'
        print('*** Begin Patch\n'+prefix+'\n'.join('+'+s for s in text.splitlines())+'\n*** End Patch')
    else:
        assert (ROOT/TARGET).read_text(encoding='utf8')==text,'Font subset stale; regenerate using --patch'
        print(f'PASS Chinese subset: {count} Han glyphs, {size} bytes, unchanged original glyph payloads')
